import { test, expect } from '@playwright/test'
import { call, client, login } from './helpers'
import { emptyDiary } from '../../lib/diary/format.mjs'

test('diary API enforces authentication, ownership, calendar dates and atomic versions', async ({ playwright, request }) => {
  expect((await request.get('/api/diary')).status()).toBe(401)
  const a = await client(playwright), b = await client(playwright, 'b')
  const path = '/api/diary/2091-03-12'
  const original = { ...emptyDiary(), text: 'Private diary A', cards: [{ id: 'small-note', text: 'A little joy', color: 'sage' }], strokes: [{ id: 'drawing', color: 'blue', width: 4, points: [[0.1, 0.2], [0.8, 0.9]] }] }
  expect((await a.get('/api/diary/2026-02-30')).status()).toBe(400)
  expect((await a.get('/api/diary/0000-01-01')).status()).toBe(400)
  expect((await a.put(path, { headers: { Origin: 'https://elsewhere.test' }, data: { version: 0, document: original } })).status()).toBe(403)
  expect((await a.put(path, { data: { document: original } })).status()).toBe(400)
  expect((await a.put(path, { data: { version: 0, document: { ...original, strokes: [{ id: 'x', width: 4, color: 'ink', points: [[-1, 0]] }] } } })).status()).toBe(400)
  const saved = await call(a, path, 'PUT', { version: 0, document: original })
  expect(saved.version).toBe(1)
  expect((await call(b, path)).version).toBe(0)
  expect((await call(b, '/api/diary')).some((row) => row.preview === original.text)).toBe(false)
  await call(b, path, 'PUT', { version: 0, document: { ...emptyDiary(), text: 'Private B' } })
  const race = await Promise.all(['first update', 'second update'].map((text) => a.put(path, { data: { version: saved.version, document: { ...original, text } } })))
  expect(race.map((response) => response.status()).sort()).toEqual([200, 409])
  const current = await call(a, path)
  expect(current.version).toBe(2)
  expect(current.document.cards).toEqual(original.cards)
  expect(current.document.strokes).toEqual(original.strokes)
  const stale = await call(a, path, 'PUT', { version: 0, document: emptyDiary() }, 409)
  expect(stale.current.version).toBe(2)
  const exported = await call(a, '/api/profile/export')
  expect(exported.diary_entries.find((row) => row.entry_date === '2091-03-12').document).toEqual(current.document)
  await a.dispose(); await b.dispose()
})
test('notebook text, cards, drawing, mood and paper survive reload on phone and desktop', async ({ page, context, playwright }) => {
  await login(context)
  const a = await client(playwright)
  await call(a, '/api/profile', 'PATCH', { settings: { theme: 'light', language: 'ru' } })
  await page.goto('/app/diary?day=2091-03-13')
  await page.getByRole('textbox', { name: 'Запись в дневнике', exact: true }).fill('Сегодня был хороший день.')
  await page.getByRole('button', { name: 'Заметка', exact: true }).click()
  await page.getByRole('textbox', { name: 'Маленькая заметка 1', exact: true }).fill('Выпить чай на балконе')
  await page.getByRole('button', { name: 'Радостно', exact: true }).click()
  await page.getByRole('button', { name: 'Клетка', exact: true }).click()
  await page.getByRole('button', { name: 'Рисовать', exact: true }).click()
  const drawing = page.locator('.diary-drawing svg')
  await drawing.scrollIntoViewIfNeeded()
  const box = await drawing.boundingBox()
  await page.mouse.move(box.x + box.width * 0.2, box.y + box.height * 0.3)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * 0.7, box.y + box.height * 0.6, { steps: 12 })
  await page.mouse.up()
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  await expect(page.locator('.diary-save-state')).toHaveText('Все изменения сохранены')
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Запись в дневнике', exact: true })).toHaveValue('Сегодня был хороший день.')
  await expect(page.getByRole('textbox', { name: 'Маленькая заметка 1', exact: true })).toHaveValue('Выпить чай на балконе')
  await expect(page.getByRole('button', { name: 'Радостно', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.diary-drawing path')).toHaveCount(1)
  await expect(page.locator('.diary-paper')).toHaveClass(/diary-paper-grid/)
  for (const theme of ['light', 'dark']) {
    await call(a, '/api/profile', 'PATCH', { settings: { theme } })
    for (const width of [390, 768, 1440]) {
      await page.setViewportSize({ width, height: 950 })
      await page.reload()
      await expect(page.locator('.diary-paper')).toBeVisible()
      await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1)
      await page.screenshot({ path: `test-results/diary-${width}-${theme}.png`, fullPage: true })
    }
  }
  await a.dispose()
})
test('a stale diary tab keeps local work and offers an explicit version choice', async ({ page, context, playwright }) => {
  await login(context)
  const a = await client(playwright)
  await call(a, '/api/profile', 'PATCH', { settings: { language: 'ru' } })
  await page.goto('/app/diary?day=2091-03-14')
  const text = page.getByRole('textbox', { name: 'Запись в дневнике', exact: true })
  await expect(text).toBeVisible()
  await call(a, '/api/diary/2091-03-14', 'PUT', { version: 0, document: { ...emptyDiary(), text: 'Другая вкладка' } })
  await text.fill('Моя мысль')
  await expect(page.getByText('Страница изменилась в другом окне', { exact: true })).toBeVisible()
  await expect(text).toHaveValue('Моя мысль')
  expect((await call(a, '/api/diary/2091-03-14')).document.text).toBe('Другая вкладка')
  await page.getByRole('button', { name: 'Сохранить мой вариант', exact: true }).click()
  await expect(page.locator('.diary-save-state')).toHaveText('Все изменения сохранены')
  expect((await call(a, '/api/diary/2091-03-14')).document.text).toBe('Моя мысль')
  await a.dispose()
})
